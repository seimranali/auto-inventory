// Builds release/ for MANUAL upload in the Cloudflare dashboard (no wrangler deploy needed):
//
//   release/worker.js        one self-contained Worker script (API + embedded React app)
//   release/1-schema.sql     run first in the D1 console
//   release/2-demo-data.sql  optional demo data (Harukaze Motors)
//   release/UPLOAD-GUIDE.md  step-by-step dashboard instructions
//
// Usage: node scripts/build-release.mjs [--admin-password=…]   (password for the demo data's Admin)
import { execSync, execFileSync } from 'child_process';
import { createRequire } from 'module';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const dist = path.resolve(root, '../frontend/dist');
const out = path.join(root, 'release');
const require = createRequire(import.meta.url);
const esbuild = require('esbuild'); // ships with wrangler

const args = Object.fromEntries(process.argv.slice(2).map(a => { const [k, v] = a.replace(/^--/, '').split('='); return [k, v ?? true]; }));

// 1. Frontend build
console.log('• Building frontend…');
execSync('npm run build', { cwd: path.resolve(root, '../frontend'), stdio: 'ignore' });

// 2. Embed every file in frontend/dist (text as-is, binary as base64)
const TEXT = /\.(html|js|css|svg|json|txt|map)$/i;
const files = {};
(function walk(dir) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, f.name);
    if (f.isDirectory()) { walk(p); continue; }
    if (f.name === '_headers' || f.name.endsWith('.map')) continue; // headers are set in code
    const key = '/' + path.relative(dist, p).split(path.sep).join('/');
    files[key] = TEXT.test(f.name) ? { data: fs.readFileSync(p, 'utf8') } : { b64: true, data: fs.readFileSync(p).toString('base64') };
  }
})(dist);
const embedded = path.join(root, 'src/embedded-assets.js');
fs.writeFileSync(embedded, `// GENERATED by scripts/build-release.mjs — do not edit\nexport default ${JSON.stringify(files)};\n`);

// 3. Bundle into one ES-module Worker script
console.log('• Bundling Worker…');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
await esbuild.build({
  entryPoints: [path.join(root, 'src/release-entry.js')],
  bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', minify: true,
  outfile: path.join(out, 'worker.js'),
  banner: { js: `// Auto Inventory — Cloudflare Worker release ${new Date().toISOString().slice(0, 10)}. Bindings required: DB (D1), UPLOADS (R2).` },
});
fs.rmSync(embedded);

// 4. SQL files
fs.copyFileSync(path.join(root, 'migrations/0001_init.sql'), path.join(out, '1-schema.sql'));
console.log('• Generating demo data…');
execFileSync(process.execPath, [path.join(here, 'export-seed.mjs'), '--demo', ...(args['admin-password'] ? [`--admin-password=${args['admin-password']}`] : [])],
  { cwd: root, stdio: ['ignore', 'ignore', 'ignore'] });
fs.copyFileSync(path.join(root, 'seed/seed.sql'), path.join(out, '2-demo-data.sql'));

// 5. Guide
fs.copyFileSync(path.join(root, 'UPLOAD-GUIDE.md'), path.join(out, 'UPLOAD-GUIDE.md'));

const kb = f => (fs.statSync(path.join(out, f)).size / 1024).toFixed(0) + ' KB';
console.log(`\nRelease ready in worker/release/
  worker.js         ${kb('worker.js')}  (${Object.keys(files).length} embedded files)
  1-schema.sql      ${kb('1-schema.sql')}
  2-demo-data.sql   ${kb('2-demo-data.sql')}   Admin: admin@autoinventory.local / ${args['admin-password'] || 'admin123'}
  UPLOAD-GUIDE.md`);
