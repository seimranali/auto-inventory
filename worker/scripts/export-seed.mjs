// Builds worker/seed/seed.sql for D1.
//
//   node scripts/export-seed.mjs --demo                 Japanese demo dataset (backend/scripts/demo-data.mjs)
//   node scripts/export-seed.mjs                        export the local backend database (backend/data/auto-inventory.db)
//
// Options: --admin-email=… --admin-password=…  (initial Admin; default admin@autoinventory.local / admin123)
//          --user-password=…                     password given to exported/demo users (default demo1234)
//
// Local passwords use scrypt, which Workers can't run, so every user is re-hashed with PBKDF2 using the passwords above.
// Photos are NOT included: upload them again after deploying (or copy backend/data/uploads to R2 with the same names).
import { execFileSync } from 'child_process';
import { createRequire } from 'module';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const backend = path.resolve(here, '../../backend');
const require = createRequire(path.join(backend, 'package.json'));
const Database = require('better-sqlite3');

const args = Object.fromEntries(process.argv.slice(2).map(a => { const [k, v] = a.replace(/^--/, '').split('='); return [k, v ?? true]; }));
const ADMIN_EMAIL = (args['admin-email'] || 'admin@autoinventory.local').toLowerCase();
const ADMIN_PASSWORD = args['admin-password'] || 'admin123';
const USER_PASSWORD = args['user-password'] || 'demo1234';

// ---- source database
let file;
if (args.demo) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ai-demo-'));
  // demo-data.mjs opens <cwd>/data/auto-inventory.db, so run it in an empty temp dir
  execFileSync(process.execPath, [path.join(backend, 'scripts/demo-data.mjs')], { cwd: tmp, stdio: ['ignore', 'inherit', 'ignore'] });
  file = path.join(tmp, 'data/auto-inventory.db');
} else {
  file = path.join(backend, 'data/auto-inventory.db');
  if (!fs.existsSync(file)) throw new Error(`No local database at ${file}`);
}
const src = new Database(file, { readonly: true });

// ---- PBKDF2 hashes in the Worker's format (pbkdf2$iter$salt$hash)
const hex = b => Buffer.from(b).toString('hex');
async function pbkdf2(password) {
  const salt = crypto.getRandomValues(new Uint8Array(16));
  const key = await crypto.subtle.importKey('raw', new TextEncoder().encode(password), 'PBKDF2', false, ['deriveBits']);
  const bits = await crypto.subtle.deriveBits({ name: 'PBKDF2', hash: 'SHA-256', salt, iterations: 100000 }, key, 256);
  return `pbkdf2$100000$${hex(salt)}$${hex(bits)}`;
}

// ---- SQL generation
const lit = v => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const d1Columns = table => {
  const sql = fs.readFileSync(path.join(here, '../migrations/0001_init.sql'), 'utf8');
  const m = new RegExp(`CREATE TABLE IF NOT EXISTS ${table} \\(([\\s\\S]*?)\\n\\);`).exec(sql);
  return new Set([...m[1].matchAll(/(?:^|,)\s*([a-z_]+) (?:TEXT|INTEGER|REAL)/gm)].map(x => x[1]));
};
function inserts(table, rows) {
  if (!rows.length) return [];
  const allowed = d1Columns(table);
  const cols = Object.keys(rows[0]).filter(c => allowed.has(c)); // drop local-only columns
  return rows.map(r => `INSERT INTO ${table} (${cols.join(',')}) VALUES (${cols.map(c => lit(r[c])).join(',')});`);
}

const out = [
  '-- Generated by worker/scripts/export-seed.mjs — replaces ALL data in the D1 database',
  'DELETE FROM sessions;', 'DELETE FROM login_attempts;', 'DELETE FROM vehicle_images;', 'DELETE FROM vehicles;',
  'DELETE FROM parties;', 'DELETE FROM users;', 'DELETE FROM company;',
];
out.push(...inserts('company', src.prepare('SELECT * FROM company WHERE id = 1').all()));
out.push(...inserts('parties', src.prepare('SELECT * FROM parties').all()));
out.push(...inserts('vehicles', src.prepare('SELECT * FROM vehicles').all().map(v => ({ ...v, auction_sheet: null })))); // files not migrated

// Users: Admin first, then everyone else with the shared password
const users = src.prepare('SELECT * FROM users').all().filter(u => u.email.toLowerCase() !== ADMIN_EMAIL);
const rows = [{ id: crypto.randomUUID(), name: 'Administrator', email: ADMIN_EMAIL, role: 'Admin', active: 1, password_hash: await pbkdf2(ADMIN_PASSWORD) }];
for (const u of users) rows.push({ ...u, password_hash: await pbkdf2(USER_PASSWORD), last_login: null });
out.push(...inserts('users', rows));

const dest = path.join(here, '../seed/seed.sql');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out.join('\n') + '\n');
const count = t => src.prepare(`SELECT COUNT(*) n FROM ${t}`).get().n;
console.log(`Wrote ${path.relative(process.cwd(), dest)}: ${count('vehicles')} vehicles, ${count('parties')} parties, ${rows.length} users
  Admin: ${ADMIN_EMAIL} / ${ADMIN_PASSWORD}${users.length ? `\n  Other users: password "${USER_PASSWORD}"` : ''}`);
